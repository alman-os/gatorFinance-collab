export type Copy = (typeof I18N)[Language];

interface I18nContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  L: Copy;
  categoryLabel: (category: string) => string;
  valueLabel: (value: string) => string;
}

const I18nContext = createContext<I18nContextValue>({
  language: "en",
  setLanguage: () => undefined,
  L: I18N.en,
  categoryLabel: (category) => category,
  valueLabel: (value) => value,
});

function initialLanguage(): Language {
  const stored = localStorage.getItem("gatorfinance-language");
  if (stored === "en" || stored === "es") return stored;
  return navigator.language.toLowerCase().startsWith("es") ? "es" : "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(initialLanguage);
  const L = I18N[language];

  useEffect(() => {
    localStorage.setItem("gatorfinance-language", language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    L,
    categoryLabel: (category) =>
      (L.categories as Record<string, string>)[category] ?? category.replace(/_/g, " ").toUpperCase(),
    valueLabel: (rawValue) =>
      (L.values as Record<string, string>)[rawValue] ?? rawValue.replace(/_/g, " ").toUpperCase(),
  }), [L, language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

export function translatedMigrationMessage(
  message: string,
  importedTransactions: number,
  L: Copy,
) {
  if (message.startsWith("Migrated ")) return L.settings.migrationCount(importedTransactions);
  if (message === "Current database already contains transactions; legacy data was left untouched.") {
    return L.settings.migrationCurrent;
  }
  if (message === "Legacy migration was already checked.") return L.settings.migrationChecked;
  if (message === "No legacy database found.") return L.settings.migrationMissing;
  return message;
}
